param(
    [string]$RepositoryRoot = (Join-Path $PSScriptRoot '../..')
)

$ErrorActionPreference = 'Stop'

function Write-GeneratedFile([string]$Path, [string]$Content) {
    if ((Test-Path -LiteralPath $Path) -and [IO.File]::ReadAllText($Path) -ceq $Content) {
        return
    }

    [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($Path)) | Out-Null
    [IO.File]::WriteAllText($Path, $Content, [Text.UTF8Encoding]::new($true))
}

$engine = Join-Path (Resolve-Path -LiteralPath $RepositoryRoot) 'Engine'
$apiDirectory = Join-Path $engine 'Include/API/ECSProcess'
[string[]]$names = @(Get-ChildItem -LiteralPath $apiDirectory -Filter '*API.h' -File |
    ForEach-Object { $_.BaseName })
[Array]::Sort($names, [StringComparer]::Ordinal)

# File names determine the API type, member name, and engine-side factory.
$includes = @()
$members = @()
$accessors = @()
$initializers = @()
foreach ($name in $names) {
    if ($name -cnotmatch '^[A-Z][A-Za-z0-9]*API$') {
        throw "Invalid ECSProcess API file name: $name.h"
    }

    $stem = $name.Substring(0, $name.Length - 3)
    $member = 'm_' + [char]::ToLowerInvariant($stem[0]) + $stem.Substring(1)
    $includes += '#include "../ECSProcess/' + $name + '.h"'
    $members += "        ECSProcessBinding<$name> $member;"
    $accessors += "        static constexpr auto Member(std::type_identity<$name>) noexcept { return &ECSProcessAPI::$member; }"
    $initializers += "            .$member = { .m_api = $($name)Impl::CreateAPI() },"
}

$header = @"
// Generated by GenerateECSProcessAPI.ps1.
#ifndef _ECS_PROCESS_API_GENERATED_H_
#define _ECS_PROCESS_API_GENERATED_H_

#include <type_traits>

$($includes -join "`n")

namespace Hestia
{
    struct ECSProcessAPI
    {
$($members -join "`n")

        template<class API>
        ECSProcessBinding<API>& Get() noexcept { return this->*Member(std::type_identity<API>{}); }

        template<class API>
        const ECSProcessBinding<API>& Get() const noexcept { return this->*Member(std::type_identity<API>{}); }

    private:
$($accessors -join "`n")
    };

#if defined(HESTIA_ENGINE_INTERNAL)
    ECSProcessAPI CreateECSProcessAPI() noexcept;
#endif
}

#endif // _ECS_PROCESS_API_GENERATED_H_
"@

$source = @"
// Generated by GenerateECSProcessAPI.ps1.
#include "pch.h"
#include "API/ECSProcessAPI.h"

namespace Hestia
{
    ECSProcessAPI CreateECSProcessAPI() noexcept
    {
        return {
$($initializers -join "`n")
        };
    }
}
"@

Write-GeneratedFile (Join-Path $engine 'Include/API/Generated/ECSProcessAPI.generated.h') ($header + "`n")
Write-GeneratedFile (Join-Path $engine 'Source/API/Generated/ECSProcessAPI.generated.cpp') ($source + "`n")
